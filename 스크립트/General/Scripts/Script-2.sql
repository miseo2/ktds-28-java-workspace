--4. 3번째로 많은 사원이 수행중인 직무의 이름과 사원 수를 조회하시오.
-- 부서별 사원의 수
SELECT D.DEPARTMENT_NAME 
     , COUNT(E.EMPLOYEE_ID ) AS EMP_CNT
  FROM EMPLOYEES E
 INNER JOIN DEPARTMENTS D
    ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
 GROUP BY D.DEPARTMENT_NAME
;
-- COUNT별 순으로 사원이 많은 순으로 정렬
SELECT DEPARTMENT_NAME
     , EMP_CNT 
     , DENSE_RANK() OVER( ORDER BY EMP_CNT DESC) AS RANK
  FROM (SELECT D.DEPARTMENT_NAME 
		     , COUNT(E.EMPLOYEE_ID ) AS EMP_CNT
		  FROM EMPLOYEES E
		 INNER JOIN DEPARTMENTS D
		    ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
		 GROUP BY D.DEPARTMENT_NAME)
;
-- RANK를 쓰기 위해 인라인뷰 사용
SELECT DEPARTMENT_NAME
     , EMP_CNT 
  FROM (SELECT DEPARTMENT_NAME
		     , EMP_CNT 
		     , DENSE_RANK() OVER( ORDER BY EMP_CNT ASC) AS RANK
		  FROM (SELECT D.DEPARTMENT_NAME 
				     , COUNT(E.EMPLOYEE_ID ) AS EMP_CNT
				  FROM EMPLOYEES E
				 INNER JOIN DEPARTMENTS D
				    ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
				 GROUP BY D.DEPARTMENT_NAME))
 WHERE RANK IN 3
;
