-- 입사일이 가장 빠른 사원 + RANK까지 ORDER BY안에 함수로 작성 안해도 되기때문에
SELECT FIRST_NAME 
     , HIRE_DATE
     , ROW_NUMBER() OVER( ORDER BY HIRE_DATE ASC) AS RANK
  FROM EMPLOYEES
;
-- RANK 사용하기 위해서 인라인 뷰 사용
SELECT FIRST_NAME 
	 , TO_CHAR(HIRE_DATE, 'YYYY-MM-DD') 
